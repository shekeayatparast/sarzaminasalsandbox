async function seedBlog() {
  console.log("🌱 Seeding blog posts...");

  for (const p of POSTS) {
    const existing = await db.blogPost.findUnique({ where: { slug: p.slug } });
    if (existing) {
      console.log(`   ✓ '${p.title}' already exists — refreshing content.`);
      await db.blogPost.update({
        where: { slug: p.slug },
        data: {
          title: p.title,
          excerpt: p.excerpt,
          content: p.content,
          coverImage: p.coverImage,
          tags: p.tags,
          published: true,
        },
      });
    } else {
      await db.blogPost.create({
        data: {
          slug: p.slug,
          title: p.title,
          excerpt: p.excerpt,
          content: p.content,
          coverImage: p.coverImage,
          tags: p.tags,
          published: true,
        },
      });
      console.log(`   ✓ Created '${p.title}'`);
    }
  }

  const total = await db.blogPost.count();
  console.log(`   ✓ Done. Total posts in DB: ${total}`);
}

seedBlog()
  .catch((e) => {
    console.error("Seed failed:", e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
